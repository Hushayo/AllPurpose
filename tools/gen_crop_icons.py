#!/usr/bin/env python3
"""Generate src/com/hush/allpurpose/CropIcons.java — the crop market's guild emoji.

Discord rejects SVG and only takes PNG/JPEG/GIF for custom emoji, so each crop's
16x16 item texture is fetched, upscaled x8 with NEAREST (keeps the pixel art
crisp instead of blurring it), and embedded as base64 in a small Java class the
plugin uploads once per guild (see DiscordStatusBoard#uploadEmoji).

Source: misode/mcmeta @ assets — a mirror of the vanilla resource pack that
tracks upstream, so no Mojang jar has to be shipped with the repo.

Usage:  python tools/gen_crop_icons.py           (writes the .java next to this repo)
        python tools/gen_crop_icons.py --check   (fetch + report, write nothing)
"""

import argparse
import base64
import io
import os
import sys
import urllib.request

from PIL import Image

BASE = "https://raw.githubusercontent.com/misode/mcmeta/assets/assets/minecraft/textures/"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   os.pardir, "src", "com", "hush", "allpurpose", "CropIcons.java")

# crop key in the EconomyShopGUI crops shop -> candidate texture paths (first hit wins)
CROPS = {
    "wheat":             ["item/wheat"],
    "wheat_seeds":       ["item/wheat_seeds"],
    "carrot":            ["item/carrot"],
    "potato":            ["item/potato"],
    "beetroot":          ["item/beetroot"],
    "beetroot_seeds":    ["item/beetroot_seeds"],
    "melon":             ["block/melon_side", "item/melon_slice"],
    "melon_seeds":       ["item/melon_seeds"],
    "pumpkin":           ["block/pumpkin_side", "item/pumpkin_pie"],
    "pumpkin_seeds":     ["item/pumpkin_seeds"],
    "cactus":            ["block/cactus_side"],
    "kelp":              ["item/kelp"],
    "dried_kelp":        ["item/dried_kelp"],
    "dried_kelp_block":  ["block/dried_kelp_side", "block/dried_kelp_top"],
    "sugar_cane":        ["item/sugar_cane"],
    "sugar":             ["item/sugar"],
    "bamboo":            ["item/bamboo"],
    "nether_wart":       ["item/nether_wart"],
    "sweet_berries":     ["item/sweet_berries"],
    "glow_berries":      ["item/glow_berries"],
    "honeycomb":         ["item/honeycomb"],
    "chorus_fruit":      ["item/chorus_fruit"],
    "chorus_flower":     ["block/chorus_flower"],
    "egg":               ["item/egg"],
    "cocoa_beans":       ["item/cocoa_beans"],
    "torchflower_seeds": ["item/torchflower_seeds"],
    "pitcher_pod":       ["item/pitcher_pod"],
    "brown_mushroom":    ["block/brown_mushroom", "item/brown_mushroom"],
    "red_mushroom":      ["block/red_mushroom", "item/red_mushroom"],
    "crimson_fungus":    ["block/crimson_fungus"],
    "warped_fungus":     ["block/warped_fungus"],
    "hay_block":         ["block/hay_block_side", "block/hay_block_top"],
    "bee_nest":          ["block/bee_nest_side", "block/bee_nest_front"],
    "beehive":           ["block/beehive_side", "block/beehive_front"],
    "bone_meal":         ["item/bone_meal"],
}

SIZE = 128  # what Discord renders at


def fetch(path):
    url = BASE + path + ".png"
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read()


def to_emoji_png(raw):
    img = Image.open(io.BytesIO(raw)).convert("RGBA")
    if img.width != img.height:  # keep the square canvas, pad instead of crop
        side = max(img.width, img.height)
        square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
        square.paste(img, ((side - img.width) // 2, (side - img.height) // 2))
        img = square
    img = img.resize((SIZE, SIZE), Image.NEAREST)
    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True)
    return buf.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="report only, write nothing")
    args = ap.parse_args()

    icons, missing, total = [], [], 0
    for key in sorted(CROPS):
        png = None
        for cand in CROPS[key]:
            try:
                png = to_emoji_png(fetch(cand))
                print("  %-18s %-28s %6d bytes" % (key, cand, len(png)))
                break
            except Exception as e:  # noqa: BLE001 - report and try the next candidate
                last = e
        if png is None:
            missing.append(key)
            print("  %-18s MISSING (%s)" % (key, last))
            continue
        icons.append((key, png))
        total += len(png)

    print("%d/%d icons, %d bytes of PNG data" % (len(icons), len(CROPS), total))
    if missing:
        print("missing (unicode fallback at runtime): %s" % ", ".join(missing))
    if args.check or not icons:
        return 1 if missing else 0

    lines = [
        "package com.hush.allpurpose;",
        "",
        "/**",
        " * GENERATED by tools/gen_crop_icons.py - do not hand-edit.",
        " * Vanilla crop item textures (misode/mcmeta @ assets, the resource-pack",
        " * mirror) upscaled x8 and embedded as PNG, because Discord rejects SVG",
        " * emoji uploads and only accepts PNG/JPEG/GIF. The bot uploads each of",
        " * these once as a guild emoji named crop_&lt;key&gt; (DiscordStatusBoard",
        " * #uploadEmoji) and reuses the id forever; an icon missing here just",
        " * falls back to a unicode glyph on the board.",
        " */",
        "public final class CropIcons {",
        "",
        "    private CropIcons() {}",
        "",
    ]
    for key, png in icons:
        b64 = base64.b64encode(png).decode("ascii")
        lines.append("    // crop_%s: %d PNG bytes" % (key, len(png)))
        lines.append("    private static final String CROP_%s =" % key.upper())
        chunks = [b64[i:i + 100] for i in range(0, len(b64), 100)]
        for i, ch in enumerate(chunks):
            sep = ";" if i == len(chunks) - 1 else " +"
            lines.append('            "%s"%s' % (ch, sep))
        lines.append("")
    lines.append("    /** PNG bytes for a crop key (e.g. \"wheat\"), or null. */")
    lines.append("    public static byte[] get(String key) {")
    lines.append("        if (key == null) return null;")
    lines.append("        try {")
    for key, _ in icons:
        lines.append('            if ("%s".equals(key)) return java.util.Base64.getDecoder().decode(CROP_%s);'
                     % (key, key.upper()))
    lines.append("        } catch (Exception e) {")
    lines.append("            return null;")
    lines.append("        }")
    lines.append("        return null;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d bytes)" % (OUT, os.path.getsize(OUT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
